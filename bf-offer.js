/* Единый слой оффера на статьях lp.sandowfitness.ru ------------------------
 *
 * Зачем файл. До 11.11.2026 оффер жил по-разному: на 61 статье был вписан
 * вручную «Black Friday», а на 70 статьях стоял прежний текст «Первое занятие
 * бесплатное». Половина сайта показывала акцию, половина — нет (вопрос Ольги
 * 11.11.2026: «почему без оффера?»).
 *
 * Здесь оффер собран в одно место и привязан к дате:
 *   * до 15 ноября 2026 включительно на всех статьях показывается
 *     «Чёрная пятница»;
 *   * с 16 ноября всё само возвращается к спокойному тексту про первое
 *     занятие — руками ничего снимать не нужно;
 *   * когда появится следующий оффер, добавляется ещё один период в СПИСОК
 *     ниже, и он сам включится в свою дату.
 *
 * Файл лежит в корне сайта и подключается одной строкой на каждой статье:
 *   <script src="/bf-offer.js" defer></script>
 * Откат: убрать эту строку — страницы вернутся к тому, что написано в них.
 */
(function () {
  'use strict';

  // ── Периоды акций. Проверяются сверху вниз, работает первый подходящий.
  var ПЕРИОДЫ = [
    {
      с: '2026-10-20', по: '2026-11-15',
      название: 'Чёрная пятница',
      // Кнопка в шапке статьи
      кнопка: 'Хочу лучшие условия',
      // Строка под кнопкой в шапке
      строка: 'Сейчас в клубе Black Friday — условия лучше обычных. ' +
              'Мы недалеко от метро Нижегородская.',
      // Нижний блок призыва
      ярлык: 'Black Friday',
      заголовок: 'Black Friday в «Сандов Фитнес»',
      подпись: 'Расскажем условия и подберём удобное время. Оставьте номер — ' +
               'перезвоним, или позвоните сами.'
    }
  ];

  // ── Что показываем, когда акции нет. Тексты взяты дословно с тех статей,
  //    где оффера не было: после 15 ноября страницы вернутся именно к ним.
  var ОБЫЧНО = {
    кнопка: 'Хочу попробовать бесплатно',
    строка: 'Первое занятие в клубе бесплатное. ' +
            'Мы недалеко от метро Нижегородская.',
    ярлык: 'Первое занятие',
    заголовок: 'Хотите начать — но не знаете, с чего?',
    подпись: 'Позвоните или напишите в Телеграм — ответим на вопросы, подберём ' +
             'удобное время и покажем зал. Первая тренировка бесплатная.'
  };

  function сегодня() {
    var д = new Date();
    // местное время пользователя, формат ГГГГ-ММ-ДД
    var г = д.getFullYear();
    var м = ('0' + (д.getMonth() + 1)).slice(-2);
    var ч = ('0' + д.getDate()).slice(-2);
    return г + '-' + м + '-' + ч;
  }

  function действующийПериод() {
    var с = сегодня();
    for (var i = 0; i < ПЕРИОДЫ.length; i++) {
      if (с >= ПЕРИОДЫ[i].с && с <= ПЕРИОДЫ[i].по) return ПЕРИОДЫ[i];
    }
    return null;
  }

  function заменить(элемент, текст) {
    if (!элемент) return;
    if ((элемент.textContent || '').trim() === текст) return;
    элемент.textContent = текст;
  }

  function применить() {
    var период = действующийПериод();
    var нужно = период || ОБЫЧНО;

    // 1. Кнопка в шапке статьи (ведёт в бота с пометкой «статья»)
    var кнопка = document.querySelector('.bf-hero-cta .btn');
    if (кнопка) заменить(кнопка, нужно.кнопка);

    // 2. Строка под кнопкой в шапке
    var строка = document.querySelector('.cta-form-note');
    if (строка) заменить(строка, нужно.строка);

    // 3. Кнопка отправки внутри формы (её текст тоже про оффер)
    var отправить = document.querySelector('.cta-form .qform button');
    if (отправить) заменить(отправить, нужно.кнопка);

    // 4. Нижний блок призыва: ярлык, заголовок, подпись
    var блок = document.querySelector('.cta-form .cf-text');
    if (блок) {
      заменить(блок.querySelector('.tag'), нужно.ярлык);
      заменить(блок.querySelector('h2'), нужно.заголовок);
      заменить(блок.querySelector('p'), нужно.подпись);
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', применить);
  } else {
    применить();
  }
})();

