def боты() -> None:
    for имя, токен in [("бот для клиентов", КЛИЕНТСКИЙ),
                       ("бот отдела продаж", СЛУЖЕБНЫЙ)]:
        if not токен:
            continue
        try:
            о = requests.get(f"https://api.telegram.org/bot{токен}/getWebhookInfo",
                             timeout=40).json().get("result", {})
        except Exception:
            плохо(f"{имя}: не удалось спросить Telegram")
            continue
        if not о.get("url"):
            плохо(f"{имя}: не подключён к серверу — сообщения не доходят")
            continue
        ждут = о.get("pending_update_count", 0)
        ошибка = о.get("last_error_message")
        if ждут > 5:
            плохо(f"{имя}: {ждут} необработанных сообщений")
        elif ошибка and о.get("last_error_date", 0) > (
                datetime.now(timezone.utc) - timedelta(hours=6)).timestamp():
            плохо(f"{имя}: свежая ошибка «{ошибка}»")
        else:
            хорошо(f"{имя} принимает сообщения")


def порог_по_расписанию(crone: list) -> float | None:
    """Сколько часов задача может молчать, судя по её собственному расписанию.

    04.10.2026: до этого все задачи мерились общим порогом 26 часов, и Ольга
    получала «давно не выполнялись» по задачам, которые и не должны идти
    каждый день: недельный scorecard (окно понедельника), сборка образа на
    push, разовое письмо в Тильду (502 ч). Настоящая находка — суточный отчёт
    Богородицка, падавший с NameError и не уходивший вовсе, — тонула в этом
    шуме. Теперь порог выводится из cron самой задачи, а задачи без расписания
    не проверяются: они не могут «опоздать».

    11.10.2026: частым задачам поставлено 12 часов вместо 6. Измерено по
    журналам: «Будильник сервисов» (cron каждые 10 минут) в жизни идёт с
    зазорами до 8,6 ч, «SLA-эскалация заявок» — до 14 ч: расписание GitHub на
    бесплатных раннерах опаздывает на часы, и половина проверок была бы
    ложной. Шести часов не хватает даже на нормальный ритм, а работы сторожа
    не отменяет: настоящие отказы видны по «падают подряд».
    """
    пороги = []
    for выражение in crone:
        поля = выражение.split()
        if len(поля) != 5:
            continue
        минута, _час, день, _месяц, дн_нед = поля
        if минута.startswith("*/") or минута == "*":
            пороги.append(12)           # частая задача: полсуток тишины — уже плохо
        elif минута.isdigit():
            if дн_нед not in ("*", "?"):
                пороги.append(8 * 24)   # раз в неделю
            elif день not in ("*", "?"):
                пороги.append(33 * 24)  # раз в месяц
            else:
                пороги.append(26)       # раз в день
        else:
            пороги.append(12)
    return min(пороги) if пороги else None


def задачи() -> None:
    """Облачные задачи: давно ли был успешный прогон и не падают ли подряд."""
    сроки = {
        "Заявки из карточки Яндекса": 8,
        "Отчёт о звонках": 12,
        "Задачи по звонкам": 12,
        "Звонки — пропущенные и ночные": 12,
        "Конверсии отдела продаж": 26,
        "Планы менеджерам": 26,
        "Охрана сайта": 26,
        "Проверка голосового тренажёра": 30,
        "Трафик — еженедельно": 8 * 24,
        "Сверка состава отдела": 8 * 24,
        "Health score новичков": 8 * 24,
        "Трафик — ежемесячно": 33 * 24,
        # 11.10.2026. Две задачи живут только на расписании GitHub (в
        # расписании будильника их нет), а оно опаздывает: у «Будильника
        # сервисов» зазоры до 8,6 ч, у «SLA-эскалации заявок» — до 14 ч.
        # Пороги поставлены по факту, иначе сторож ругался бы на норму.
        # Правильное лечение — перевести их в расписание будильника
        # (cloudflare/cron-worker/worker.js), тогда пороги можно вернуть.
        "Будильник сервисов": 12,
        "SLA-эскалация заявок": 18,
    }
    сломанные = []
    молчащие = []
    без_расписания = []
    под_проверкой = 0
    кэш_расписаний = {}
    # Следы запусков, которые делает будильник: по ним виден его ритм.
    запуски_будильника: list[float] = []
    for репо in ("aum151-commits/sandow-lp", "aum151-commits/sandow-automation"):
        о = requests.get(f"https://api.github.com/repos/{репо}/actions/workflows",
                         headers=ЗАГОЛОВКИ, timeout=40)
        if о.status_code != 200:
            плохо(f"не удалось прочитать список задач в {репо}")
            continue
        for wf in о.json().get("workflows", []):
            if wf["state"] != "active" or "pages-build" in wf["path"]:
                continue
            # Расписание берём из файла задачи: без него нельзя судить,
            # опоздала она или идёт в своём темпе (push, ручной запуск).
            ключ = (репо, wf["path"])
            if ключ not in кэш_расписаний:
                файл = requests.get(
                    f"https://api.github.com/repos/{репо}/contents/{wf['path']}",
                    headers={**ЗАГОЛОВКИ, "Accept": "application/vnd.github.raw+json"},
                    timeout=40)
                текст = файл.text if файл.status_code == 200 else ""
                # Обе кавычки: cron бывает и в одинарных, и в двойных.
                # Раньше ловились только одинарные — задача с двойными
                # молча попадала в «без расписания» и не проверялась вовсе.
                кэш_расписаний[ключ] = (
                    re.findall(r"cron:\s*['\"]([^'\"]+)['\"]", текст)
                    if "schedule:" in текст else [])
            порог_расписания = порог_по_расписанию(кэш_расписаний[ключ])
            if порог_расписания is None:
                без_расписания.append(wf["name"])
                continue
            под_проверкой += 1
            прогоны = requests.get(
                f"https://api.github.com/repos/{репо}/actions/workflows/{wf['id']}/runs?per_page=6",
                headers=ЗАГОЛОВКИ, timeout=40).json().get("workflow_runs", [])
            # Запуск будильника видно по workflow_dispatch — и он считается
            # даже идущим: для «жив ли будильник» итог прогона не важен.
            for r in прогоны:
                if r["event"] == "workflow_dispatch":
                    запуски_будильника.append(часов_назад(r["created_at"]))
            # Идущие прямо сейчас прогоны ни о чём не говорят: у них ещё нет
            # итога. Без этого проверка первым делом ругалась сама на себя —
            # свой собственный запуск она видела как «ни одного успешного».
            прогоны = [r for r in прогоны if r["conclusion"]]
            если_нет = сроки.get(wf["name"], порог_расписания)
            успешные = [r for r in прогоны if r["conclusion"] == "success"]
            if not успешные:
                if прогоны:
                    сломанные.append(wf["name"])
                continue
            прошло = часов_назад(успешные[0]["created_at"])
            if прошло > если_нет:
                молчащие.append(f"{wf['name']} ({int(прошло)} ч)")
            подряд = 0
            for r in прогоны:
                if r["conclusion"] == "failure":
                    подряд += 1
                elif r["conclusion"]:
                    break
            if подряд >= 3:
                сломанные.append(wf["name"])

    if сломанные:
        плохо("падают подряд: " + ", ".join(sorted(set(сломанные))))
    if молчащие:
        плохо("давно не выполнялись: " + ", ".join(sorted(set(молчащие))))
    if not сломанные and not молчащие:
        хорошо(f"все облачные задачи выполняются вовремя "
               f"(по расписанию {под_проверкой}, без расписания "
               f"{len(set(без_расписания))} — их не считаем)")

    # Ритм будильника — по его следу. Задачи, которые он дёргает, идут
    # круглосуточно (конверсии и встречи — раз в час, звонки — каждые
    # 10 минут днём), поэтому два с половиной часа тишины уже означают, что
    # будильник встал, а расписание GitHub подхватит задачи только через
    # часы. Прежняя проверка «по последнему тику» этого не видела вовсе:
    # будильник такого поля не отдаёт.
    if запуски_будильника:
        тишина = min(запуски_будильника)
        if тишина > 2.5:
            плохо(f"будильник задач молчит {int(тишина * 60)} минут — "
                  f"задачи идут только по опаздывающему расписанию GitHub")
        else:
            хорошо(f"будильник задач держит ритм (последний запуск "
                   f"{int(тишина * 60)} минут назад)")


