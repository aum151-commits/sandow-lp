# -*- coding: utf-8 -*-
"""Будильник облачных задач клуба «Сандов Фитнес».

Зачем он есть. Задачи выполняет GitHub Actions, но время там соблюдается
«по возможности»: замерено за 01.09.2026 — «каждые полчаса» обернулось
четырьмя запусками за сутки, «каждые десять минут» — тремя. Человек,
которому не перезвонили, попадал в отчёт через три часа вместо получаса.

Поэтому время задаёт этот сервис, а GitHub только делает работу.
Снаружи в него раз в несколько минут стучится бесплатный сторонний
будильник (cron-job.org / UptimeRobot) по адресу /cron/<секрет>. Наружу
отдан только адрес: токен GitHub остаётся здесь, в переменных сервиса,
и в исходный код не попадает — поэтому код может лежать в открытом
репозитории.

Почему отдельный сервис, а не внутри лид-бота: у Render раз за разом
отваливается доступ к приватным репозиториям клуба (это уже случалось
с «Тренер Хабом» и голосовым тренажёром), и восстановить его может
только человек руками. Открытый репозиторий такого доступа не требует,
значит эту часть нельзя сломать чужой настройкой.
"""
import os
import threading
from datetime import datetime, timedelta, timezone

import requests
from flask import Flask, jsonify

app = Flask(__name__)

МОСКВА = timezone(timedelta(hours=3))

СЕКРЕТ = os.environ.get("CRON_SECRET", "").strip()
ТОКЕН = os.environ.get("GH_DISPATCH_TOKEN", "").strip()
РЕПО = os.environ.get("GH_REPO", "aum151-commits/sandow-lp").strip()

# задача → (запускать раз в N минут, в какие часы по Москве).
# Часы те же, что в самих задачах; здесь они продублированы, потому что
# решение о запуске принимается тут.
РАСПИСАНИЕ = {
    "calls_watch.yml":     (30, range(10, 22)),   # пропущенные звонки
    "call_tasks.yml":      (10, range(10, 22)),   # напоминания перезвонить
    # Всё, что пишет людям в чат заявок, работает 10:00–22:00: ночью туда
    # идут только настоящие обращения клиентов (бот, формы сайта), а
    # накопившееся за ночь закрывает один отчёт в десять утра.
    "calls.yml":           (30, range(10, 22)),   # отчёт о звонках
    "yandex_requests.yml": (20, range(0, 24)),    # заявки с карточки Яндекса
    "plans.yml":           (30, range(8, 19)),    # планы и просрочки
    "renewals.yml":        (60, range(10, 19)),   # отчёт по звонкам 13 и 17
    "conversions.yml":     (60, range(0, 24)),    # конверсии отдела продаж
    "appointments.yml":    (60, range(0, 24)),    # встречи из звонков
    "site_guard.yml":     (120, range(0, 24)),    # охрана сайта
    "cloud_guard.yml":    (180, range(0, 24)),    # сторож самих задач
    "check_all.yml":      (720, range(9, 11)),    # общая проверка, утром
}

# сервисы, которые надо держать в тонусе: бесплатный Render усыпляет их
# после четверти часа тишины, а спящий бот отвечает на заявку с задержкой.
БУДИТЬ = [
    "https://sandow-lead-bot.onrender.com/health",
]

_СЛОТЫ = {}
_ЗАМОК = threading.Lock()
_ПОСЛЕДНИЙ = {"когда": None, "запущено": []}


def _слот(шаг, сейчас):
    """Номер отрезка внутри суток.

    Считаем от начала суток, а не «сколько прошло с прошлого раза»: тогда
    повторный стук в ту же минуту не запускает задачу дважды, а перезапуск
    сервиса не сбивает сетку.
    """
    return (сейчас.hour * 60 + сейчас.minute) // шаг


def _работа(имена):
    for имя in имена:
        try:
            о = requests.post(
                f"https://api.github.com/repos/{РЕПО}/actions/workflows/{имя}/dispatches",
                headers={"Authorization": f"Bearer {ТОКЕН}",
                         "Accept": "application/vnd.github+json"},
                json={"ref": "main"}, timeout=40)
            print(f"[расписание] {имя} → {о.status_code}", flush=True)
        except Exception as сбой:
            print(f"[расписание] {имя} не запустилась: {сбой}", flush=True)
    for адрес in БУДИТЬ:
        try:
            requests.get(адрес, timeout=40)
        except Exception:
            pass


@app.route("/cron/<secret>", methods=["GET", "POST"])
def тик(secret):
    if not СЕКРЕТ or secret != СЕКРЕТ:
        return jsonify(ok=False), 404
    if not ТОКЕН:
        return jsonify(ok=False, ошибка="нет токена GitHub"), 500

    сейчас = datetime.now(МОСКВА)
    пора = []
    for имя, (шаг, часы) in РАСПИСАНИЕ.items():
        if сейчас.hour not in часы:
            continue
        слот = _слот(шаг, сейчас)
        with _ЗАМОК:
            if _СЛОТЫ.get(имя) == слот:
                continue
            _СЛОТЫ[имя] = слот
        пора.append(имя)

    # Запускаем в стороне от ответа: внешний будильник не должен ждать,
    # пока GitHub примет десяток запросов, иначе он сочтёт вызов неудачным.
    threading.Thread(target=_работа, args=(пора,), daemon=True).start()

    _ПОСЛЕДНИЙ["когда"] = сейчас.strftime("%d.%m %H:%M")
    if пора:
        _ПОСЛЕДНИЙ["запущено"] = пора
    return jsonify(ok=True, время=_ПОСЛЕДНИЙ["когда"], запущено=пора)


# ------------------------------------------------------- собственный завод
#
# Кто будит будильник. Бесплатный Render усыпляет сервис после четверти
# часа без входящих запросов, поэтому сам по себе он бы замолчал. Обычный
# ответ — сторонний пингер, но у клуба уже был опыт: вход в такие сервисы
# закрыт капчей, и завести новый может только человек руками. Здесь сервис
# держит себя сам: раз в несколько минут ходит запросом на собственный
# публичный адрес. Для Render это обычный входящий запрос — значит сервис
# не засыпает, а заодно выполняется расписание.
#
# Если цикл всё же оборвётся (перезапуск платформы, сбой), сервис разбудит
# запасной пинг из GitHub — он приходит редко и неточно, но возобновляет
# цикл, дальше тот идёт сам.

САМ_СЕБЯ = int(os.environ.get("SELF_TICK_SECONDS", "300"))
МОЙ_АДРЕС = os.environ.get("RENDER_EXTERNAL_URL", "").rstrip("/")


def _завод():
    import time
    while True:
        time.sleep(САМ_СЕБЯ)
        if not (МОЙ_АДРЕС and СЕКРЕТ):
            continue
        try:
            requests.get(f"{МОЙ_АДРЕС}/cron/{СЕКРЕТ}", timeout=60)
        except Exception as сбой:
            print(f"[завод] не достучался до себя: {сбой}", flush=True)


if МОЙ_АДРЕС and СЕКРЕТ:
    threading.Thread(target=_завод, daemon=True).start()
    print(f"[завод] запущен, шаг {САМ_СЕБЯ} с, адрес {МОЙ_АДРЕС}", flush=True)


@app.route("/health")
@app.route("/")
def здоровье():
    return jsonify(ok=True, сервис="будильник задач «Сандов Фитнес»",
                   задач=len(РАСПИСАНИЕ),
                   настроен=bool(СЕКРЕТ and ТОКЕН),
                   последний_тик=_ПОСЛЕДНИЙ["когда"],
                   москва=datetime.now(МОСКВА).strftime("%d.%m %H:%M"))


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", 5000)))
