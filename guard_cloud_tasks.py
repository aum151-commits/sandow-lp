# -*- coding: utf-8 -*-
"""Сторож облачных задач клуба.

Повод: с 25.08.2026 задачи в приватном репозитории не запускались вообще —
кончились бесплатные минуты GitHub. Пять суток не собирались заявки с
карточки Яндекса, и никто этого не заметил: сообщений о таком GitHub не шлёт.

Что делает: смотрит на все задачи с расписанием в обоих репозиториях и
проверяет две вещи —
  * когда в последний раз был УСПЕШНЫЙ прогон (молчание дольше срока — тревога);
  * не падают ли прогоны подряд (три подряд — тревога).

Тревога уходит Ольге в личку и повторяется не чаще раза в сутки на задачу,
чтобы сломанная задача не звонила каждые три часа.
"""
from __future__ import annotations

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ТОКЕН_GH = os.environ.get("PRIVATE_REPO_TOKEN", "").strip()
БОТ = os.environ.get("ALERT_BOT_TOKEN", "").strip()
ЧАТ = os.environ.get("ALERT_CHAT_ID", "").strip()

СОСТОЯНИЕ = Path("state_cloud_guard.json")

# сколько задача может молчать, прежде чем это станет тревогой.
# Считаем щедро: расписание GitHub само по себе опаздывает на часы.
# Сроки щедрые не от лени: расписание GitHub само опаздывает на часы
# (измерено — «каждые 20 минут» приходило раз в 4,4 часа). Ставить порог
# в 3 часа значит завести сторожа, который звенит на исправной системе,
# а на такого перестают обращать внимание.
СРОКИ = {
    "Заявки из карточки Яндекса": 8,      # заявки клиентов — самое важное
    "Отчёт о звонках": 12,
    "Задачи по звонкам": 12,
    "Конверсии отдела продаж": 26,        # раз в сутки достаточно
    "Проверка голосового тренажёра": 30,
    "Будильник сервисов": 8,
    "Сторож лид-бота": 8,
    "Отзывы — новые, рейтинг, снятые": 26,
    "Проверка автоматики": 26,
    "Сторож облачных задач": 8,
    # 11.10.2026. Недельные отчёты уходили по понедельникам, а мерились общим
    # сроком в 26 часов — и сторож считал их молчащими КАЖДЫЙ день. Именно эти
    # два ключа лежали в состоянии за 11.10 («молчит 147 ч»), хотя отчёты
    # работают: они уходят раз в неделю.
    "Scorecard недели": 8 * 24,
    "Богородицк — недельный отчёт": 8 * 24,
    # Недельные и месячные задачи. Без своих сроков они попадали под общий
    # порог в 26 часов и звенели каждый вторник, хотя работали правильно —
    # сторож, который поднимает ложную тревогу, обесценивает настоящую.
    "Трафик — еженедельно": 8 * 24,
    "Сверка состава отдела": 8 * 24,
    "Health score новичков": 8 * 24,
    "Трафик — ежемесячно": 33 * 24,
}
# Сколько прогонов подряд должно упасть, чтобы это считалось поломкой, а не
# случайностью. Два — мало: сеть на GitHub рвётся, и одиночное падение бывает
# и у здоровой задачи. Три — уже система.
ПОРОГ_ПОДРЯД = 3

СРОК_ПО_УМОЛЧАНИЮ = 26

ЗАГОЛОВКИ = {"Authorization": f"Bearer {ТОКЕН_GH}",
             "Accept": "application/vnd.github+json"}


def состояние() -> dict:
    if СОСТОЯНИЕ.exists():
        try:
            return json.loads(СОСТОЯНИЕ.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            pass
    return {}


def сообщить(текст: str) -> None:
    if not (БОТ and ЧАТ):
        print("не задан бот для тревог")
        return
    requests.post(f"https://api.telegram.org/bot{БОТ}/sendMessage",
                  data={"chat_id": ЧАТ, "text": текст}, timeout=40)


def есть_расписание(репо: str, путь: str, кэш: dict) -> bool:
    """Есть ли у задачи своё расписание (cron).

    11.10.2026: без этой проверки сторож начал ругаться на задачи, которые и не
    должны идти по часам, — «Образ будильника» (собирается только при изменении
    папки `cron/**`) и «Письмо Тильде про вебвизор» (разовое, руками). Молчание
    для них — норма, а не поломка. Тем же правилом живёт сторож автоматики
    (`check_all.py`): задачи без расписания не проверяются, они не могут
    «опоздать».
    """
    ключ = (репо, путь)
    if ключ not in кэш:
        r = requests.get(f"https://api.github.com/repos/{репо}/contents/{путь}",
                         headers={**ЗАГОЛОВКИ, "Accept": "application/vnd.github.raw+json"},
                         timeout=40)
        текст = r.text if r.status_code == 200 else ""
        кэш[ключ] = ("schedule:" in текст and "cron:" in текст)
    return кэш[ключ]


def проверить(репо: str) -> list[str]:
    беды = []
    r = requests.get(f"https://api.github.com/repos/{репо}/actions/workflows",
                     headers=ЗАГОЛОВКИ, timeout=40)
    if r.status_code != 200:
        return [f"{репо}: не получить список задач (код {r.status_code})"]

    сейчас = datetime.now(timezone.utc)
    кэш_расписаний: dict = {}
    for wf in r.json().get("workflows", []):
        имя, путь = wf["name"], wf["path"]
        if "pages-build" in путь or wf["state"] != "active":
            continue
        if not есть_расписание(репо, путь, кэш_расписаний):
            continue  # идёт по push или руками — опоздать не может

        runs = requests.get(
            f"https://api.github.com/repos/{репо}/actions/workflows/{wf['id']}/runs?per_page=10",
            headers=ЗАГОЛОВКИ, timeout=40,
        ).json().get("workflow_runs", [])

        # 11.10.2026, две правки в этом месте.
        #
        # 1) Идущие прямо сейчас прогоны ни о чём не говорят: у них ещё нет
        #    итога. Без этой строки сторож 11.10 в 21:01 посмотрел на прогон
        #    отзывов, начавшийся в 21:00, увидел conclusion=None и объявил
        #    «ни одного успешного прогона за последние 1 попыток» — Ольга
        #    получила тревогу о полностью исправной задаче (все её прогоны за
        #    сутки зелёные, а тот, на который смотрел сторож, завершился
        #    успешно через две минуты). Тот же урок, что в check_all.py.
        #
        # 2) Считаем ВСЕ прогоны, а не только по расписанию GitHub. Раньше
        #    задачи и правда жили на нём; теперь большинство дёргает будильник
        #    (workflow_dispatch), а GitHub своё расписание выполняет редко — у
        #    отзывов за сутки три таких прогона из двухсот. По ним судить о
        #    здоровье задачи нельзя.
        по_всем = [x for x in runs if x.get("conclusion")]
        if not по_всем:
            continue  # у задачи нет ни одного завершённого прогона

        успешные = [x for x in по_всем if x["conclusion"] == "success"]
        срок = СРОКИ.get(имя, СРОК_ПО_УМОЛЧАНИЮ)

        # Каждая беда — пара (устойчивый ключ, текст). Ключ НЕ содержит
        # меняющихся чисел: раньше ключом была вся строка вместе с
        # «5 ч назад», поэтому при каждом прогоне она выглядела новой и
        # про одну и ту же поломку сторож писал каждые 3 часа. Ольга
        # 24.09.2026: «мне нужно получать информацию только о реальных
        # проблемах». Один настоящий повод — одно сообщение в сутки.
        if not успешные:
            беды.append((f"{имя}|нет успешных",
                         f"«{имя}»: ни одного успешного прогона за последние "
                         f"{len(по_всем)} попыток"))
            continue

        # 19.10.2026: задача МОЖЕТ запускаться и падать каждый раз, а сторож
        # молчал — он смотрел только на давность последнего успеха. Живой
        # случай этого дня: две задачи падали с 11:15 из-за ошибки в коде, но
        # последний успешный прогон был свежим, и до срока в 12 часов оставалось
        # десять. Ольга узнала бы об этом только к полуночи — или не узнала бы
        # вовсе. Теперь отдельная беда: «падает подряд» — это видно через
        # несколько минут, а не через полдня.
        подряд = 0
        for прогон in по_всем:              # от свежих к старым
            if прогон["conclusion"] == "failure":
                подряд += 1
            else:
                break
        if подряд >= ПОРОГ_ПОДРЯД:
            когда_упал = datetime.fromisoformat(
                по_всем[0]["created_at"].replace("Z", "+00:00"))
            минут = (сейчас - когда_упал).total_seconds() / 60
            беды.append((f"{имя}|падает подряд",
                         f"«{имя}»: падает {подряд} прогона подряд, последний — "
                         f"{минут:.0f} мин назад. Задача запускается, но не работает."))

        когда = datetime.fromisoformat(успешные[0]["created_at"].replace("Z", "+00:00"))
        часов = (сейчас - когда).total_seconds() / 3600
        if часов > срок:
            беды.append((f"{имя}|молчит",
                         f"«{имя}»: последний успешный прогон {часов:.0f} ч назад "
                         f"(допустимо {срок} ч)"))
            continue

        подряд = 0
        for x in по_всем:
            if x["conclusion"] == "failure":
                подряд += 1
            else:
                break
        if подряд >= 3:
            беды.append((f"{имя}|падает",
                         f"«{имя}»: {подряд} падения подряд"))

    return беды


def main() -> None:
    if not ТОКЕН_GH:
        print("нет токена GitHub")
        return

    все = []
    for репо in ("aum151-commits/sandow-lp", "aum151-commits/sandow-automation"):
        найдено = проверить(репо)
        for ключ, текст in найдено:
            все.append((ключ, текст))
            print(f"   {текст}")
        print(f"{репо}: проблем {len(найдено)}")

    st = состояние()
    сегодня = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    новые = [(к, т) for к, т in все if st.get(к) != сегодня]

    # Решённые проблемы забываем — иначе состояние растёт вечно (было
    # 14 844 байта из одних «N ч назад»), а повтор той же поломки через
    # неделю не был бы виден как новый.
    живые = {к for к, _ in все}
    for к in list(st):
        if к not in живые:
            del st[к]

    if новые:
        текст = ("Облачные задачи требуют внимания:\n\n"
                 + "\n".join(f"• {т}" for _, т in новые)
                 + "\n\nЧаще всего это либо кончились минуты GitHub, либо "
                   "истёк доступ к сервису. Логи: github.com/aum151-commits")
        сообщить(текст)
        print("тревога отправлена, пунктов:", len(новые))
        for к, _ in новые:
            st[к] = сегодня
    else:
        print("всё в порядке или уже сообщали сегодня")

    # Пишем состояние всегда, а не только при отправке: иначе очистка
    # решённых проблем не сохранилась бы и файл рос бы дальше.
    СОСТОЯНИЕ.write_text(json.dumps(st, ensure_ascii=False, indent=2),
                         encoding="utf-8")


if __name__ == "__main__":
    main()
