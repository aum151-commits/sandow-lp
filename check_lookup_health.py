# -*- coding: utf-8 -*-
"""Утренняя проверка: готов ли справочник звонков к началу работы отдела.

Зачем. Отдел продаж начинает работу в 10:00. Если ночная выгрузка из 1С не
прошла, сторож звонков будет подписывать пропущенные вчерашними данными —
и никто об этом не узнает, пока Ольга не спросит. Требование Ольги
12.10.2026: «а можно сразу узнать, что выгрузка не удалась и исправить это
до начала работы в 10:00 отдела продаж?». Эта проверка отвечает ровно на
этот вопрос: она идёт в 08:50 и 09:20 по Москве и пишет Ольге, если что-то
не так — за час до открытия, а не после.

Что проверяет:
    1. ночная выгрузка из 1С в облаке — последний прогон задачи
       one_c_clients.yml завершился успешно;
    2. справочник в Яндекс.Облаке — свежий (обновлён не позже 12 часов
       назад) и не обеднённый (людей не меньше 5000);
    3. облачная функция отвечает — то есть связка «функция → бакет» жива,
       имена по номерам действительно достаются.

Когда всё хорошо — молчит. Исключение: по понедельникам приходит одна
короткая строка «всё в порядке»: иначе нельзя отличить «всё хорошо» от
«проверка сама перестала запускаться».

Зависимостей нет — только стандартная библиотека, чтобы проверка не могла
упасть из-за недоступного pip.

Переменные окружения:
    LOOKUP_URL, LOOKUP_TOKEN — адрес и ключ облачной функции;
    GH_TOKEN                 — токен GitHub (читает прогоны задачи выгрузки);
    TG_TOKEN                 — бот для сообщения;
    CHECK_REPORT             — «1», чтобы прислать строку «всё в порядке» даже
                               когда всё хорошо (для ручного запуска и понедельника).

Чат берётся жёстко — личный чат Ольги (220285486), как в missed_watch.py и
night_calls_report.py. Это не мелочь: правило §0г требует, чтобы проверки
уходили ТОЛЬКО куратору в личку, а не в рабочие группы. Переменной
окружения этот адрес можно переопределить, но по умолчанию он личный.
"""
from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timedelta, timezone

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

РЕПО_ВЫГРУЗКИ = "aum151-commits/sandow-automation"
ЗАДАЧА_ВЫГРУЗКИ = "one_c_clients.yml"

ЧАСОВ_СВЕЖЕСТИ = 12       # ночная выгрузка в 23:30, проверка в 08:50 — это 9 ч
МИНИМУМ_ЛЮДЕЙ = 5000      # пустая или обрезанная выгрузка

ОТЧЁТ_ВСЕГДА = os.environ.get("CHECK_REPORT", "").strip() in ("1", "true", "да")

# Личный чат Ольги — тот же, куда уходит предпросмотр сторожа.
ЛИЧКА_ОЛЬГИ = "220285486"


def env(имя: str) -> str:
    return (os.environ.get(имя) or "").strip()


def спросить_json(адрес: str, шапки: dict | None = None, таймаут: int = 40):
    запрос = urllib.request.Request(адрес, headers=шапки or {})
    with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
        return json.loads(ответ.read())


def проверить_выгрузку() -> tuple[bool, str]:
    """Последний прогон ночной выгрузки из 1С."""
    токен = env("GH_TOKEN")
    if not токен:
        return False, "не задан GH_TOKEN — про прогон выгрузки ничего не знаю"
    шапки = {"Authorization": f"Bearer {токен}",
             "Accept": "application/vnd.github+json"}
    адрес = (f"https://api.github.com/repos/{РЕПО_ВЫГРУЗКИ}/actions/workflows/"
             f"{ЗАДАЧА_ВЫГРУЗКИ}/runs?per_page=5")
    try:
        данные = спросить_json(адрес, шапки)
    except Exception as e:  # noqa: BLE001
        return False, f"прогоны выгрузки недоступны ({type(e).__name__})"

    запуски = данные.get("workflow_runs", [])
    if not запуски:
        return False, "у задачи выгрузки нет ни одного прогона"
    последний = запуски[0]
    когда = datetime.strptime(последний["created_at"], "%Y-%m-%dT%H:%M:%SZ").replace(
        tzinfo=timezone.utc)
    возраст = datetime.now(timezone.utc) - когда
    ссылка = последний["html_url"]

    if последний.get("status") != "completed":
        return False, f"выгрузка сейчас выполняется (прогон №{последний['run_number']})"
    if последний.get("conclusion") != "success":
        return False, (f"выгрузка из 1С не прошла: {последний.get('conclusion')} "
                       f"(прогон №{последний['run_number']}, {ссылка})")
    if возраст > timedelta(hours=20):
        return False, (f"выгрузка не запускалась {int(возраст.total_seconds() // 3600)} ч "
                       f"(последний прогон №{последний['run_number']}, {ссылка})")
    return True, f"выгрузка прошла (прогон №{последний['run_number']})"


def проверить_справочник() -> tuple[bool, str, dict]:
    """Справочник глазами сторожа: что отдаёт облачная функция."""
    адрес = env("LOOKUP_URL")
    ключ = env("LOOKUP_TOKEN")
    if not адрес or not ключ:
        return False, "адрес или ключ справочника не заданы в секретах", {}
    try:
        данные = спросить_json(адрес + "?" + urllib.parse.urlencode({"key": ключ}))
    except urllib.error.HTTPError as e:
        return False, f"функция ответила {e.code} — справочник недоступен", {}
    except Exception as e:  # noqa: BLE001
        return False, f"функция не отвечает ({type(e).__name__})", {}

    if not данные.get("ok"):
        return False, f"функция ответила ошибкой: {str(данные)[:120]}", {}

    людей = int(данные.get("людей") or 0)
    обновлён_текст = str(данные.get("обновлено") or "")
    try:
        обновлён = datetime.strptime(обновлён_текст, "%d.%m.%Y %H:%M")
    except ValueError:
        return False, f"не понял дату обновления справочника: «{обновлён_текст}»", данные

    возраст = datetime.now() - обновлён
    if возраст > timedelta(hours=ЧАСОВ_СВЕЖЕСТИ):
        return False, (f"справочник обновлён {обновлён_текст} — это "
                       f"{int(возраст.total_seconds() // 3600)} ч назад"), данные
    if людей < МИНИМУМ_ЛЮДЕЙ:
        return False, f"в справочнике всего {людей} человек — похоже на обрезанную выгрузку", данные
    return True, f"справочник свежий: {людей} человек, обновлён {обновлён_текст}", данные


def отправить(текст: str) -> bool:
    токен = env("TG_TOKEN")
    чат = env("TG_CHAT") or ЛИЧКА_ОЛЬГИ
    if not токен:
        print("нет бота — сообщение не отправлено")
        print(текст)
        return False
    данные = urllib.parse.urlencode({"chat_id": чат, "text": текст,
                                     "disable_web_page_preview": "true"}).encode()
    try:
        with urllib.request.urlopen(
                f"https://api.telegram.org/bot{токен}/sendMessage", данные,
                timeout=40) as ответ:
            тело = json.loads(ответ.read())
            print("сообщение отправлено:", тело.get("ok"))
            return bool(тело.get("ok"))
    except Exception as e:  # noqa: BLE001
        print("сообщение не ушло:", type(e).__name__, str(e)[:150])
        print(текст)
        return False


def main() -> int:
    проблемы = []
    хорошее = []

    ок, что = проверить_выгрузку()
    print(("  ок: " if ок else "  ПЛОХО: ") + что)
    (хорошее if ок else проблемы).append(что)

    ок, что, данные = проверить_справочник()
    print(("  ок: " if ок else "  ПЛОХО: ") + что)
    (хорошее if ок else проблемы).append(что)

    сейчас = datetime.now()
    понедельник = сейчас.weekday() == 0

    if проблемы:
        строки = ["<b>Справочник звонков не готов</b>", ""]
        строки.append("Что не так:")
        строки += [f"• {п}" for п in проблемы]
        строки.append("")
        строки.append("Значит, пропущенные звонки будут подписаны вчерашними "
                      "данными или без имени. Время до открытия отдела — "
                      "поправить ещё можно.")
        отправить("\n".join(строки))
        return 1   # красный прогон — так сбой видно и в GitHub, а не только в Телеграме

    if ОТЧЁТ_ВСЕГДА or понедельник:
        отправить("Справочник звонков в порядке: " + "; ".join(хорошее) + ".")
    print("всё в порядке")
    return 0


if __name__ == "__main__":
    sys.exit(main())
